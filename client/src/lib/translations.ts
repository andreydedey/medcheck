/** Translates a symptom name (snake_case from dataset) to Portuguese. */
export function translateSymptom(name: string): string {
  const key = name.trim().toLowerCase()
  return SYMPTOM_PT[key] ?? name.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())
}

/** Translates a disease name (lowercase from dataset) to Portuguese. */
export function translateDisease(name: string): string {
  const key = name.trim().toLowerCase()
  return DISEASE_PT[key] ?? name.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())
}
